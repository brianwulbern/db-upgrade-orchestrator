#!/usr/bin/env bash
# run_gaps.sh --version <v> [--dry-run]
#
# Retry, EXACTLY ONCE, every catalog DB that is not yet green on <version> — i.e. the DBs
# `./rollup_status.sh --version <v>` shows as FAIL/UNKNOWN/NEVER-RUN. It assembles a temp
# manifest from the DBs' existing manifest lines and runs it serially (one start_batch pass;
# it does NOT loop). Run rollup again afterward to see what's left.
#
# Guard: it will NOT launch while another batch is running — two separate batch processes do
# not share the Oracle "max 1" cap, so overlapping runs could put two Oracle upgrades on the
# box at once. (--dry-run still shows the plan while a run is in flight.)
set -uo pipefail
cd "$(dirname "$0")"

VER="" DRY=0 CATALOG="jobs.manifest" ATTEMPTED_ONLY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)   VER="${2:-}"; shift 2 ;;
    --catalog)   CATALOG="${2:-}"; shift 2 ;;
    --attempted) ATTEMPTED_ONLY=1; shift ;;   # gaps = only DBs actually run on this version
    --dry-run)   DRY=1; shift ;;
    -h|--help) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "usage: $0 --version <v> [--catalog FILE] [--attempted] [--dry-run]" >&2; exit 2 ;;
  esac
done
[[ -n "$VER" ]] || { echo "need --version (e.g. --version 2.q3.2)" >&2; exit 2; }
norm() { echo "${1,,}" | sed -E 's/^app-bundle-//; s/[^0-9a-z.]//g'; }

# latest-known result per modl on this version (newest run-ts wins)
declare -A LATEST=()
for ts in $(ls -1d batch-runs/*/ 2>/dev/null | sed 's#^batch-runs/##; s#/$##' | sort -r); do
  s="batch-runs/$ts/summary.txt"; [[ -f "$s" ]] || continue
  [[ "$(norm "$(cat "batch-runs/$ts/version.txt" 2>/dev/null)")" == "$(norm "$VER")" ]] || continue
  while read -r m _e r _x; do
    case "$r" in PASS|FAIL|UNKNOWN|DID-NOT-START) ;; *) continue ;; esac
    [[ -z "${LATEST[$m]:-}" ]] && LATEST[$m]="$r"
  done < <(grep -E '[[:space:]](PASS|FAIL|UNKNOWN|DID-NOT-START)[[:space:]]' "$s")
done

# catalog = the modls to consider gaps against. Default: ONE authoritative manifest (jobs.manifest),
# NOT the union of every *.manifest — a stale bucket/retry manifest lists DBs that were never part
# of this version's validation, and unioning them pulled NEVER-RUN strangers (customer-x/customer-y/…) into
# the retry. --catalog FILE picks a different manifest; --attempted narrows to only the DBs that were
# actually run on this version (the safest scope for "retry what didn't pass this cycle").
if [[ "$ATTEMPTED_ONLY" == 1 ]]; then
  mapfile -t CAT < <(printf '%s\n' "${!LATEST[@]}" | sort -u)
elif [[ -f "$CATALOG" ]]; then
  mapfile -t CAT < <(grep -hvE '^\s*#|^\s*$' "$CATALOG" 2>/dev/null | awk -F'|' 'NF>=4{gsub(/ /,"",$4); print $4}' | sort -u)
else
  echo "❌ catalog manifest not found: $CATALOG (use --catalog FILE or --attempted)" >&2; exit 1
fi

# gaps = catalog DBs whose latest result is not PASS (NEVER-RUN counts as a gap) AND whose dump
# is actually present on disk. The dump-present filter keeps stray catalog entries from old
# *.manifest files (DBs we're not staging this cycle) out of the retry — you can't re-run a dump
# you don't have, and NEVER-RUN + absent-dump is noise, not a gap.
gaps=(); nodump=()
for m in "${CAT[@]}"; do
  [[ "${LATEST[$m]:-NEVER-RUN}" == PASS ]] && continue
  line="$(grep -hE "\|[[:space:]]*${m}[[:space:]]*\|" ./*.manifest 2>/dev/null | grep -vE '^\s*#' | head -1)"
  dump="$(awk -F'|' 'NF>=2{gsub(/^[ \t]+|[ \t]+$/,"",$2); print $2}' <<<"$line")"
  if [[ -n "$dump" && -f "$dump" ]]; then gaps+=("$m"); else nodump+=("$m"); fi
done
((${#nodump[@]})) && echo "ℹ️  skipping ${#nodump[@]} not-green DB(s) with no dump present: ${nodump[*]}"
if [[ ${#gaps[@]} -eq 0 ]]; then
  echo "✅ nothing to retry — every catalog DB with a present dump is green on $VER."
  exit 0
fi

# assemble a temp manifest (.gen so it's not picked up as a catalog manifest)
gen="gaps-$(date +%Y%m%d-%H%M%S).gen"
{
  echo "# auto-generated by run_gaps.sh — not-green DBs on $VER (single retry pass)"
  echo "# engine | dump | target_db | modl | offset | heap | es_mode | flags"
  for m in "${gaps[@]}"; do
    line="$(grep -hE "\|[[:space:]]*${m}[[:space:]]*\|" ./*.manifest 2>/dev/null | grep -vE '^\s*#' | head -1)"
    if [[ -n "$line" ]]; then echo "$line"; else echo "# WARN: no manifest line found for '$m' — add one to a manifest"; fi
  done
} > "$gen"

echo "Not-green on $VER (${#gaps[@]}): ${gaps[*]}"
echo "Assembled $gen:"; grep -vE '^\s*#' "$gen" | sed 's/^/  /'
missing="$(grep -c '^# WARN:' "$gen" || true)"
[[ "$missing" -gt 0 ]] && echo "  ⚠️  $missing DB(s) had no manifest line — see WARN lines; they won't run."

if [[ $DRY -eq 1 ]]; then
  echo "(dry-run — nothing launched; temp manifest kept at $gen)"
  exit 0
fi

# launch guard — refuse to overlap a running batch
if pgrep -f '[b]atch_upgrade.sh' >/dev/null 2>&1; then
  echo "❌ a batch is currently running — wait for it (./status_batch.sh), then re-run. Not launched."
  echo "   (kept $gen; you can launch it yourself once free: BATCH_MAX_CONCURRENCY=1 ./start_batch.sh $gen)"
  exit 1
fi

echo "Launching serially (single pass)…"
BATCH_MAX_CONCURRENCY=1 ./start_batch.sh "$gen"
